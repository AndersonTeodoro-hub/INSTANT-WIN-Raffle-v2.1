export const keptraTranslations: Record<Lang, KeptraCopy> = { en, pt, es };

/** "{name}" in a text, filled; a missing value keeps its braces, so a slip shows on the page instead of vanishing. */
export function fill(template: string, values: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (whole, key: string) => (key in values ? String(values[key]) : whole));
}

/** The text before and after "{name}", for a value that is an element (a link, an address in the data face). */
export function around(template: string, key: string): [string, string] {
  const [before, after = ''] = template.split(`{${key}}`);
  return [before, after];
}

/** A failure's sentence in the page's language: this app's own sentences are translated; the bridge's come as written. */
export function clientError(message: string, lang: Lang): string {
  const key = (Object.keys(en.errors) as (keyof KeptraCopy['errors'])[]).find((name) => en.errors[name] === message);
  return key === undefined ? message : keptraTranslations[lang].errors[key];
}

/** The Keptra pages' words in the chosen language, the language itself (for numbers and dates), and say() for a failure. */
export function useKeptraCopy() {
  const [lang] = useLang();
  const t = keptraTranslations[lang];
  return { t, lang, say: (message: string) => clientError(message, lang) };
}
