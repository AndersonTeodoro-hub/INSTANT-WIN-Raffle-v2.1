// outbound HTTP
// ---------------------------------------------------------------------------

/**
 * Replaces globalThis.fetch, so mail.ts, telegram.ts, alert.ts and the DNS-over-
 * HTTPS lookup in identity.ts run their real code against a recorded transport.
 * Doubling the transport rather than the modules is what keeps the timeout, the
 * abort wiring and the request bodies under test.
 */
export const http = {
  requests: [],
  /** url pattern -> (url, init) => Response | Error */
  routes: [],
  reset() {
    http.requests.length = 0;
    http.routes.length = 0;
  },
  on(pattern, handler) {
    http.routes.push([pattern, handler]);
  },
};

/**
 * The transport before it was replaced.
 *
 * Exported so the one suite that is allowed out — the read-only checks against
 * Arbitrum One — can register a route that goes to the real network. Nothing
 * else may use it: a test that reaches a provider passes or fails on somebody
 * else's uptime.
 */
export const realFetch = globalThis.fetch;

export function installFetchDouble() {
  globalThis.fetch = async (input, init = {}) => {
    const url = typeof input === 'string' ? input : String(input?.url ?? input);
    http.requests.push({ url, init, body: init.body });
    for (const [pattern, handler] of http.routes) {
      if (url.includes(pattern)) {
        const result = await handler(url, init);
        if (result instanceof Error) throw result;
        return result;
      }
    }
    // Unprogrammed: refused rather than allowed out. A test that reaches the
    // network is a test that would pass or fail on somebody else's uptime.
    throw new Error(`[test] no double for outbound fetch to ${url}`);
  };
}

export function restoreFetch() {
  globalThis.fetch = realFetch;
}

export const jsonResponse = (body, status = 200) =>
  new Response(JSON.stringify(body), { status, headers: { 'content-type': 'application/json' } });

