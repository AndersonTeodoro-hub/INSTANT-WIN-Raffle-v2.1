/** One entry per test: which requirements it covers, and how it ended. */
export const results = [];

let currentSuite = 'unknown';
export function suite(name) {
  currentSuite = name;
}

/**
 * Declares one test.
 *
 * `requirements` is the list of SPEC-BRIDGE-V2 identifiers the test exercises.
 * The report's requirement map is built from these, so a test that covers
 * nothing declares nothing and a requirement with no test is visible as a gap
 * rather than as an omission somebody has to notice.
 */
export async function test(requirements, name, body) {
  const entry = { suite: currentSuite, requirements, name, ok: false, error: null };
  results.push(entry);
  try {
    await body();
    entry.ok = true;
  } catch (error) {
    entry.error = error instanceof Error ? (error.stack ?? error.message) : String(error);
  }
}

export { assert };

/** Builds a Request the way the platform hands one to a route. */
export function request(url, { method = 'POST', body, headers = {}, cookie } = {}) {
  const finalHeaders = {
    'content-type': 'application/json',
    'x-forwarded-for': '198.51.100.7',
    'user-agent': 'test-agent',
    ...headers,
  };
  if (cookie !== undefined) finalHeaders.cookie = cookie;
  return new Request(url, {
    method,
    headers: finalHeaders,
    body: body === undefined ? undefined : JSON.stringify(body),
  });
}

/** A logger double, so a test can read what a route recorded without a table. */
export function recordingLogger() {
  const events = [];
  return {
    correlationId: 'test-correlation',
    events,
    event: async (kind, detail = {}) => {
      events.push({ kind, detail });
    },
    failure: async (kind, error, detail = {}) => {
      events.push({ kind, detail, error });
    },
  };
}

/** A run deadline double with a fixed answer, so a test controls G4 directly. */
export function deadline(hasTime = true, remaining = 280_000) {
  return { hasTimeFor: () => hasTime, remainingMs: () => remaining };
}
