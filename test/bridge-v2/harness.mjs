/**
 * The runner, the environment and the outbound-HTTP double.
 *
 * No framework and no new dependency: node:assert and the type stripping the
 * repository already runs its V1 suite with. The one thing added over that suite
 * is that every test declares which requirements of SPEC-BRIDGE-V2 it exercises,
 * so the requirement-to-test map in the report is produced by the suite rather
 * than written alongside it and left to drift.
 *
 * CREDENTIALS. Nothing in this file or anywhere under test/ is a real key. The
 * wallet seed is the Hardhat/Anvil documentation mnemonic, which is public, whose
 * accounts are known to everybody and hold nothing on any real network. Every
 * other secret-shaped value is generated by crypto.getRandomValues at the moment
 * the process starts and exists only in this process's memory.
 */

import assert from 'node:assert/strict';

/**
 * The public Hardhat/Anvil test mnemonic. Not a secret: it is in the Hardhat
 * documentation and its addresses are known to everyone. The real derivation
 * root lives only in the Vercel environment and never in a file.
 */
export const TEST_MNEMONIC = 'test test test test test test test test test test test junk';

const randomHex = (bytes) => {
  const buffer = new Uint8Array(bytes);
  crypto.getRandomValues(buffer);
  return [...buffer].map((byte) => byte.toString(16).padStart(2, '0')).join('');
};

/** Two funder keys, generated here, used only by this process. */
export const TEST_FUNDER_KEYS = [`0x${randomHex(32)}`, `0x${randomHex(32)}`];
export const TEST_ROLE_KEY = `0x${randomHex(32)}`;
export const TEST_CRON_SECRET = randomHex(32);
export const TEST_TELEGRAM_SECRET = randomHex(32);

